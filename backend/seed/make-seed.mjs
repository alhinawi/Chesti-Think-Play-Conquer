// Generates seed/seed.sql with demo players. LOCAL USE ONLY (password for all: demo-pass-123).
// Run: node seed/make-seed.mjs
import { writeFileSync } from 'node:fs'
import { pbkdf2Sync, randomBytes } from 'node:crypto'

const names = ['Hinawi', 'Magnus', 'Hikaru', 'Judit', 'Anand', 'Fabi', 'Nepo', 'Ding']
const hash = (pw) => {
  const salt = randomBytes(16)
  return `pbkdf2$100000$${salt.toString('base64')}$${pbkdf2Sync(pw, salt, 100000, 32, 'sha256').toString('base64')}`
}
const day = 86400000
let sql = '-- Demo data, local only. Generated by make-seed.mjs. Never run on the live database.\n'
names.forEach((name, i) => {
  const id = i + 1
  sql += `INSERT INTO users (id, name, email, password_hash) VALUES (${id}, '${name}', '${name.toLowerCase()}@chesti.test', '${hash('demo-pass-123')}');\n`
  for (let g = 0; g < 6 + i * 2; g++) {
    const result = ['win', 'win', 'loss', 'draw'][(g + i) % 4]
    const at = new Date(Date.now() - g * day * 0.7).toISOString()
    sql += `INSERT INTO games (user_id, mode, opponent, color, result, pgn, moves, played_at) VALUES (${id}, 'computer', 'bot-${(g % 5) + 1}', '${g % 2 ? 'black' : 'white'}', '${result}', '1. e4 e5 2. Nf3 Nc6', ${20 + g}, '${at}');\n`
  }
  sql += `INSERT INTO scores (user_id, kind, points) VALUES (${id}, 'rush', ${10 + i * 4}), (${id}, 'puzzles', ${5 + i * 3});\n`
})
writeFileSync(new URL('./seed.sql', import.meta.url), sql)
console.log('wrote seed.sql')
